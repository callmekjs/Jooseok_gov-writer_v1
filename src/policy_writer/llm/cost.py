#   provider    model                          input_tokens   output_tokens
#   openai      gpt-4o-mini                         1,986            416
#   openai      gpt-5.6-terra                        1,985            892
#   openai      gpt-5.6-sol                          1,985          1,912
#   anthropic   claude-haiku-4-5                     3,143          1,066
#   anthropic   claude-sonnet-4-5-20250929           3,143          1,367
#   anthropic   claude-opus-4-5-20251101             3,143          1,204
#
# input 은 같은 L1~L5 프롬프트인데도 회사(토크나이저)별로만 갈린다 — Anthropic
# 쪽이 OpenAI보다 한글을 더 잘게 쪼개 토큰이 ~58% 더 많다. 이전 세션 실측치
# (컨트롤러 추가지시: 1,811~2,807)와 합치면 관측 범위는 1,811~3,143.
# 이전 상수 4,000 은 이 범위보다 항상 크다 — 이게 "모든 등급 과대 표시"의 원인.
#
# output 은 각 등급이 목표 분량(1,500자)에 얼마나 다가가는지에 따라 416~1,912
# 로 편차가 크다. gpt-4o-mini(416)를 제외한 나머지 다섯 모델이 892~1,912
# 사이에 있고, 그중 셋(1,066 / 1,204 / 1,367)만 1,000~1,400대다 — 나머지 둘
# (892, 1,912)은 그 범위 바깥이다.
#
# ★ 두 상수를 3,000 / 1,400 으로 정한 진짜 근거는 중심경향이다:
#   3,000 은 실측 input 6건의 평균과 중앙값(반올림하면 둘 다 2,564)보다 높다.
#   1,400 은 실측 output 6건의 평균(1,143)과 중앙값(1,135) 둘 다보다 높다.
#   즉 "중심경향보다 조금 높게" 잡으라는 지침을 평균·중앙값 기준으로 그대로
#   만족한다 — 아래 모델별 배율은 이 선택을 사후 검증하는 표일 뿐, 배율을
#   맞추려고 상수를 역산한 게 아니다.
#
# 검증 — (3000, 1400)으로 역산한 표시값과, 이번에 실제로 청구된(=실측 토큰
# 그대로 계산한) 금액을 모델별로 비교하면:
#
#   모델                          표시(신규)   실측 청구   배율
#   gpt-4o-mini                        2원         1원     2.00x  (1원 단위 반올림 — 아래 참고, 별도 조정 대상 아님)
#   gpt-5.6-terra                     32원        21원     1.52x
#   gpt-5.6-sol                       56원        65원     0.86x  (유일한 under-state — 아래 참고)
#   claude-haiku-4-5                  14원        12원     1.17x
#   claude-sonnet-4-5-20250929        42원        42원     1.00x
#   claude-opus-4-5-20251101          70원        64원     1.09x
#
# gpt-4o-mini 의 2.00x: 나머지 다섯을 과소표시하지 않는 한 1원 단위 반올림
# 때문에 어떤 정직한 상수를 골라도 구조적으로 못 피한다.
#
# gpt-5.6-sol 만 0.86x 로 유일하게 under-state 인 진짜 이유, 그리고 왜 그대로
# 두는가 (근거 없이 그냥 둔 게 아니라 의도적으로 받아들인 트레이드오프다):
#   (input, output) 여러 조합을 대입해 봐도, sol 의 실측 65원을 과소표시하지
#   않으면서 나머지 다섯 모델을 전부 실측 대비 2배 밑에 묶어 두는 조합은
#   없다 — sol 의 65원에 맞을 만큼 output 을 올리면(≈1,900) 이번엔
#   gpt-5.6-terra 의 표시값이 실측 대비 ~1.9배까지 뛴다. 즉 "출력이 가장 긴
#   모델 하나를 살짝 과소표시"하거나 "다른 모델을 거의 2배로 과대표시"하거나
#   둘 중 하나를 반드시 골라야 하고, 전자를 의도적으로 선택했다.
#   왜 안전한가: 화면의 "1건당 N원"은 등급을 고르는 단계에서 보여주는 견적일
#   뿐이다. 실제로 청구되는 금액은 항상 그 순간의 실측 토큰으로 다시 계산한다
#   (api/speech.py 의 meta.cost_won, 작성 이력 화면 모두 실측값을 보여준다) —
#   이 상수가 조금 낮게 잡혀 있어도 사용자가 견적보다 더 내는 일은 없다.
#
# 한계 1 — 첨부 경로는 이번 실측 대상이 아니다: 위 6건은 전부 첨부 없는
#   /api/speech/draft 다. build_l4_speech()(prompts/builder.py)는 업로드된
#   행사계획서 텍스트를 자르지 않고 그대로 프롬프트에 이어 붙이므로, 첨부가
#   있는 /api/speech/auto-draft · draft-with-docs 경로는 input 이 3,143 을
#   넘어갈 수 있다 — 그 경로에서는 이 상수가 옛 4,000 보다도 더 크게
#   과소표시한다.
#
# 한계 2 — 이 output 상수는 알려진 결함에 기대어 정했다: 416~1,912 로 편차가
#   큰 주된 이유는 저가 등급들이 1,500자 목표에 못 미치고 멈추기 때문이다 —
#   이미 Task 13 대기열에 있는, 프롬프트/모델의 알려진 결함이다. 목표를 실제로
#   채운 유일한 모델(gpt-5.6-sol)이 1,912 를 썼다. Task 13 이 이 분량 미달을
#   고치면 모든 등급의 출력이 1,900 근방으로 몰릴 것이고, 그러면 1,400 은
#   전 모델에서 과소표시로 바뀐다. ★ Task 13 이후 이 두 상수는 재검토가
#   필요하다.
TYPICAL_INPUT_TOKENS = 3000      # 실측 1,985~3,143(+과거 1,811~2,807). 평균·중앙값(2,564)보다 높다
TYPICAL_OUTPUT_TOKENS = 1400     # 실측 416~1,912. 평균(1,143)·중앙값(1,135)보다 높다 — Task 13 이후 재검토 필요


def won_for_usage(model_meta: dict, input_tokens: int, output_tokens: int) -> int:
    usd = (
        input_tokens * model_meta["in"] / 1_000_000
        + output_tokens * model_meta["out"] / 1_000_000
    )
    return round(usd * USD_TO_KRW)


def won_per_doc(model_meta: dict) -> int:
    """말씀자료 1건당 대략 얼마인지. 사용자에게 $0.000123 은 의미가 없다."""
    return won_for_usage(model_meta, TYPICAL_INPUT_TOKENS, TYPICAL_OUTPUT_TOKENS)
